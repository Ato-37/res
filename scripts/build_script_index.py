#!/usr/bin/env python3
"""Build docs/script_index.md: a catalogue of scripts/ (kind, first docstring line, whether an experiment log mentions it) without moving or deleting anything.

Scripts are flat on purpose: receipts, queue scripts and experiment logs reference them by name, so moving files would break provenance. Usage: build_script_index.py [--root REPO] [--output docs/script_index.md]
"""
from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path

KINDS = [("test_", "unit test"), ("analyze_", "analysis"), ("run_", "runner"), ("build_", "builder"), ("freeze_", "cohort freeze"), ("screen_", "screen"),
         ("verdict_", "verdict"), ("summarize_", "summary"), ("generate_", "generator"), ("qta_", "library module"), ("smoke_", "smoke")]


def kind_of(name: str) -> str:
    for prefix, label in KINDS:
        if name.startswith(prefix):
            return label
    return "other"


def first_doc_line(path: Path) -> str:
    if path.suffix != ".py":
        for line in path.read_text(errors="replace").splitlines()[:6]:
            if line.startswith("#") and not line.startswith("#!"):
                return line.lstrip("# ").strip()[:110]
        return ""
    try:
        doc = ast.get_docstring(ast.parse(path.read_text(errors="replace")))
    except SyntaxError:
        return "(syntax error)"
    return (doc or "").strip().splitlines()[0][:110] if doc else ""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    ap.add_argument("--output", type=Path, default=None)
    a = ap.parse_args()
    root = a.root
    out = a.output or root / "docs/script_index.md"
    scripts = sorted(p for p in (root / "scripts").iterdir() if p.is_file() and p.suffix in (".py", ".sh"))
    corpus = "\n".join(p.read_text(errors="replace") for p in (root / "experiments").glob("*.md"))
    corpus += "\n".join(p.read_text(errors="replace") for p in (root / "docs").glob("*.md") if p.name != out.name)
    code = {p: p.read_text(errors="replace") for p in scripts}
    rows, orphans = [], []
    for p in scripts:
        n = p.name
        in_log = n in corpus or p.stem in corpus
        used_by = [q.name for q, t in code.items() if q != p and (p.stem in t) and not q.name.startswith("test_")]
        tested = (root / "scripts" / f"test_{n}").exists() or any(q.name.startswith("test_") and p.stem in t for q, t in code.items() if q != p)
        rows.append((kind_of(n), n, first_doc_line(p), in_log, len(used_by), tested))
        if kind_of(n) not in ("unit test",) and not in_log and not used_by:
            orphans.append(n)
    kinds = {}
    for r in rows:
        kinds[r[0]] = kinds.get(r[0], 0) + 1
    lines = ["# scripts/ index", "",
             "Generated by `scripts/build_script_index.py` (do not edit by hand). Scripts stay flat because receipts, queue scripts and experiment logs reference them by file name; nothing here is a deletion recommendation.", "",
             "Counts by kind: " + ", ".join(f"{k} {v}" for k, v in sorted(kinds.items(), key=lambda x: -x[1])), "",
             f"Not mentioned in any experiment log or doc and not imported by another script ({len(orphans)}): review before any cleanup.", ""]
    lines += ["| kind | script | what | in log/doc | used by | has test |", "| --- | --- | --- | --- | --- | --- |"]
    for kind, n, doc, in_log, nused, tested in rows:
        if kind == "unit test":
            continue
        lines.append(f"| {kind} | {n} | {doc.replace('|', '/')} | {'yes' if in_log else 'no'} | {nused} | {'yes' if tested else 'no'} |")
    lines += ["", "## Orphan candidates (no reference found)", ""] + [f"- {n}" for n in orphans]
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(rows)} scripts, {len(orphans)} orphan candidates)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
